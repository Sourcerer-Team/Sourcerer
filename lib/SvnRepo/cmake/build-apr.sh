#!/bin/sh
set -e

src_dir=$1
build_dir=$2
install_dir=$3

mkdir -p "$build_dir"
mkdir -p "$install_dir/include/apr-1"
mkdir -p "$install_dir/lib"
mkdir -p "$install_dir/bin"
mkdir -p "$install_dir/build-1"

trap 'rm -f "$build_dir/buildconf.clean"' EXIT

tmp_buildconf="$build_dir/buildconf.clean"
cd "$src_dir"
tr -d '\r' < buildconf > "$tmp_buildconf"
sh "$tmp_buildconf" --with-apr="$src_dir"
cd "$build_dir"
sh "$src_dir/configure" --disable-shared --enable-static --prefix="$install_dir"

cat > "$build_dir/libtool" <<'EOF'
#!/bin/sh
set -e
mode=
while [ $# -gt 0 ]; do
    case "$1" in
        --silent|--quiet)
            shift
            ;;
        --tag=*)
            shift
            ;;
        --mode=*)
            mode=${1#--mode=}
            shift
            ;;
        *)
            break
            ;;
    esac
done

case "$mode" in
    compile)
        compiler=$1
        shift
        out=
        args=
        while [ $# -gt 0 ]; do
            case "$1" in
                -o)
                    out=$2
                    shift 2
                    ;;
                *)
                    args="$args '$1'"
                    shift
                    ;;
            esac
        done
        out_o=${out%.lo}.o
        eval set -- "$args"
        "$compiler" "$@" -o "$out_o"
        touch "$out"
        ;;
    link)
        shift
        out=
        objs=
        while [ $# -gt 0 ]; do
            case "$1" in
                -o)
                    out=$2
                    shift 2
                    ;;
                -rpath|-release)
                    shift 2
                    ;;
                *.lo)
                    objs="$objs ${1%.lo}.o"
                    shift
                    ;;
                *)
                    shift
                    ;;
            esac
        done
        base=${out%.la}
        archive=${base}.a
        eval set -- $objs
        ar cru "$archive" "$@"
        ranlib "$archive"
        cat > "$out" <<LA
# libtool archive generated by custom wrapper
dlname=''
library_names=''
old_library='$(basename "$archive")'
installed=no
shouldnotlink=no
LA
        ;;
    install)
        shift
        if [ $# -gt 0 ] && [ "${1#-}" = "$1" ]; then
            shift
        fi
        src=
        dest=
        while [ $# -gt 0 ]; do
            case "$1" in
                -c)
                    shift
                    ;;
                -m|-o|-t)
                    shift 2
                    ;;
                -*)
                    shift
                    ;;
                *)
                    if [ -z "$src" ]; then
                        src=$1
                    else
                        dest=$1
                    fi
                    shift
                    ;;
            esac
        done
        base=${src%.la}
        mkdir -p "$dest"
        cp "$src" "$dest/$(basename "$src")"
        if [ -f "$base.a" ]; then
            cp "$base.a" "$dest/$(basename "$base.a")"
        fi
        ;;
    *)
        exit 0
        ;;
esac
EOF
chmod +x "$build_dir/libtool"

for generated in "$build_dir/Makefile" "$build_dir/apr-1-config" "$build_dir/build/apr_rules.mk" "$build_dir/libtool"; do
    if [ -f "$generated" ]; then
        perl -0pi -e 's/\r\n/\n/g; s/\r/\n/g' "$generated"
    fi
done

make install

cp "$build_dir/build/apr_rules.mk" "$install_dir/build-1/apr_rules.mk"
cp "$build_dir/apr-1-config" "$install_dir/bin/apr-1-config"
for generated in "$install_dir/bin/apr-1-config" "$install_dir/build-1/apr_rules.mk" "$install_dir/lib/libapr-1.la" "$install_dir/lib/libapr-1.a" "$install_dir/lib/libapr-1.so"; do
    if [ -f "$generated" ]; then
        perl -0pi -e 's/\r\n/\n/g; s/\r/\n/g' "$generated"
    fi
done
