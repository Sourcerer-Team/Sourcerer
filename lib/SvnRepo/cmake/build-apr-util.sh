#!/bin/sh
set -e

src_dir=$1
build_dir=$2
install_dir=$3
apr_install_dir=$4
apr_src_dir=$5
expat_src_dir=$6
expat_build_dir=$7

mkdir -p "$build_dir"
mkdir -p "$install_dir/include"
mkdir -p "$install_dir/lib"
mkdir -p "$install_dir/bin"
mkdir -p "$install_dir/build"

trap 'rm -f "$build_dir/buildconf.clean"' EXIT

tmp_buildconf="$build_dir/buildconf.clean"
cd "$src_dir"
tr -d '\r' < buildconf > "$tmp_buildconf"
sh "$tmp_buildconf" --with-apr="$apr_src_dir"
cd "$build_dir"
CPPFLAGS="${CPPFLAGS} -I${expat_src_dir}/lib"
LDFLAGS="${LDFLAGS} -L${expat_build_dir}"
export CPPFLAGS
export LDFLAGS
sh "$src_dir/configure" --disable-shared --enable-static --prefix="$install_dir" --with-apr="$apr_install_dir"
sed -i "s|^INCLUDES = |INCLUDES = -I${expat_src_dir}/lib |" "$build_dir/Makefile"
sed -i "s|^APRUTIL_EXPORT_INCLUDES=\"\"|APRUTIL_EXPORT_INCLUDES=\"-I${expat_src_dir}/lib\"|" "$build_dir/export_vars.sh"

cat > "$build_dir/libtool" <<'EOF'
#!/bin/sh
set -e
mode=
while [ $# -gt 0 ]; do
    case "$1" in
        --silent|--quiet)
            shift
            ;;
        --tag=*)
            shift
            ;;
        --mode=*)
            mode=${1#--mode=}
            shift
            ;;
        *)
            break
            ;;
    esac
done

case "$mode" in
    compile)
        compiler=$1
        shift
        out=
        args=
        while [ $# -gt 0 ]; do
            case "$1" in
                -o)
                    out=$2
                    shift 2
                    ;;
                *)
                    args="$args '$1'"
                    shift
                    ;;
            esac
        done
        out_o=${out%.lo}.o
        eval set -- "$args"
        "$compiler" "$@" -o "$out_o"
        touch "$out"
        ;;
    link)
        shift
        out=
        objs=
        while [ $# -gt 0 ]; do
            case "$1" in
                -o)
                    out=$2
                    shift 2
                    ;;
                -rpath|-release)
                    shift 2
                    ;;
                *.lo)
                    objs="$objs ${1%.lo}.o"
                    shift
                    ;;
                *)
                    shift
                    ;;
            esac
        done
        base=${out%.la}
        archive=${base}.a
        eval set -- $objs
        ar cru "$archive" "$@"
        ranlib "$archive"
        cat > "$out" <<LA
# libtool archive generated by custom wrapper
dlname=''
library_names=''
old_library='$(basename "$archive")'
installed=no
shouldnotlink=no
LA
        ;;
    install)
        shift
        if [ $# -gt 0 ] && [ "${1#-}" = "$1" ]; then
            shift
        fi
        src=
        dest=
        while [ $# -gt 0 ]; do
            case "$1" in
                -c)
                    shift
                    ;;
                -m|-o|-t)
                    shift 2
                    ;;
                -*)
                    shift
                    ;;
                *)
                    if [ -z "$src" ]; then
                        src=$1
                    else
                        dest=$1
                    fi
                    shift
                    ;;
            esac
        done
        base=${src%.la}
        mkdir -p "$dest"
        cp "$src" "$dest/$(basename "$src")"
        if [ -f "$base.a" ]; then
            cp "$base.a" "$dest/$(basename "$base.a")"
        fi
        ;;
    *)
        exit 0
        ;;
esac
EOF
chmod +x "$build_dir/libtool"

for generated in "$build_dir/Makefile" "$build_dir/apu-1-config" "$build_dir/build/rules.mk" "$build_dir/libtool"; do
    if [ -f "$generated" ]; then
        perl -0pi -e 's/\r\n/\n/g; s/\r/\n/g' "$generated"
    fi
done

make install

perl -0pe 's/@apu_have_sqlite3_10@/1/g; s/@apu_have_crypto_10@/0/g; s/@apu_have_apr_iconv_10@/0/g' "$src_dir/include/apu.hwc" > "$install_dir/include/apu.h"
perl -0pe 's/@apr_has_ldap_10@/0/g' "$src_dir/include/apr_ldap.hwc" > "$install_dir/include/apr_ldap.h"
cp "$src_dir/include/apu_want.hw" "$install_dir/include/apu_want.h"
cp "$src_dir/include/private/apu_config.hw" "$install_dir/include/apu_config.h"
cp "$src_dir/include/private/apu_select_dbm.hw" "$install_dir/include/apu_select_dbm.h"

cp "$build_dir/build/rules.mk" "$install_dir/build/rules.mk"
for generated in "$install_dir/bin/apu-1-config" "$install_dir/build/rules.mk" "$install_dir/lib/libaprutil-1.la" "$install_dir/lib/libaprutil-1.a" "$install_dir/lib/libaprutil-1.so"; do
    if [ -f "$generated" ]; then
        perl -0pi -e 's/\r\n/\n/g; s/\r/\n/g' "$generated"
    fi
done
